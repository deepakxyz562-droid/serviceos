import { NextRequest, NextResponse } from 'next/server';
import {
  cloneGoogleAccountToTenant,
  ensureUniqueBgosWorkspaceSlug,
  hasWorkspaceLiveActivity,
  listUserBgosWorkspaces,
  looksLikeAutoGeneratedFallbackSlug,
} from '@/lib/bgos-workspaces';
import { ensureAndSyncBusinessChatbot } from '@/lib/bgos-business-chatbot';
import { db } from '@/lib/db';
import { getAuthUser } from '@/lib/auth';
import { invalidatePlacePayloadCache } from '@/app/api/gbp/place/route';
import { normalizeRegionState } from '@/lib/bgos-business-sanitizers';

export const dynamic = 'force-dynamic';

export interface GbpDiscoveredProfile {
  id: string;
  name: string;
  shortId: string;
  initial: string;
  isPrimary?: boolean;
  category?: string;
  address?: string;
}

export async function GET(request: NextRequest) {
  try {
    const user = await getAuthUser(request);
    if (!user || !user.tenantId) {
      return NextResponse.json({ error: 'Authentication required' }, { status: 401 });
    }
    const tenantId = user.tenantId;

    const tenant = await db.tenant.findUnique({
      where: { id: user.tenantId },
      select: { id: true, name: true, phone: true, settingsJson: true },
    });

    let tenantSettings: Record<string, any> = {};
    if (tenant?.settingsJson) {
      try {
        tenantSettings = JSON.parse(tenant.settingsJson);
      } catch {}
    }

    const socialAccounts = await db.socialAccount.findMany({
      where: {
        tenantId: user.tenantId,
        platform: 'googlebusiness',
        isActive: true,
      },
      orderBy: { updatedAt: 'desc' },
    });

    let googleEmail = '';
    const profiles: GbpDiscoveredProfile[] = [];

    for (const sa of socialAccounts) {
      let meta: Record<string, any> = {};
      if (sa.metadata) {
        try {
          meta = typeof sa.metadata === 'string' ? JSON.parse(sa.metadata) : sa.metadata;
          if (meta.googleEmail && !googleEmail) googleEmail = String(meta.googleEmail);
        } catch {}
      }

      const id = String(sa.accountId || meta.locationId || sa.id);
      const name = String(meta.locationTitle || sa.accountName || 'Google Business Profile')
        .replace(/\s*\([^)]*\)$/, '')
        .trim();
      const shortId = `#${id.slice(-4)}`;
      const initial = name.trim().charAt(0).toUpperCase() || 'B';
      const isPrimary = tenantSettings.activeGbpLocationId
        ? id === String(tenantSettings.activeGbpLocationId)
        : profiles.length === 0;

      profiles.push({
        id,
        name,
        shortId,
        initial,
        isPrimary,
        category: meta.category,
        address: meta.address,
      });
    }

    if (!googleEmail) {
      googleEmail = user.email || '';
    }

    // Honest handling: if no genuine Google Business account is connected, return empty
    if (profiles.length === 0) {
      return NextResponse.json({
        email: googleEmail,
        count: 0,
        hasConnectedGbp: false,
        activeProfileId: null,
        savedPublishingAccountId: null,
        activeProfile: null,
        profiles: [],
        phone: tenant?.phone || '',
        version: 'BGOS v2.0',
      });
    }

    // Sort profiles so the selected/active profile is first
    profiles.sort((a, b) => {
      if (a.isPrimary && !b.isPrimary) return -1;
      if (!a.isPrimary && b.isPrimary) return 1;
      return a.name.localeCompare(b.name);
    });

    const userWorkspaces = await listUserBgosWorkspaces(
      user.id,
      user.workspaceId,
      user.tenantId,
    ).catch(() => []);
    const currentWorkspaceActivity = await hasWorkspaceLiveActivity(user.tenantId).catch(() => ({
      hasActivity: false,
      reason: null,
      counts: { leads: 0, customers: 0, bookings: 0, conversations: 0, publicChats: 0, reviews: 0, posts: 0 },
    }));

    // Include any Google Business profiles already connected under other workspaces owned by this user
    const knownIds = new Set(profiles.map((p) => p.id));
    if (userWorkspaces.length > 1 || user.id) {
      const otherAccounts = await db.socialAccount
        .findMany({
          where: {
            platform: 'googlebusiness',
            isActive: true,
            OR: [
              { connectedById: user.id },
              ...(userWorkspaces.length > 0
                ? [{ tenantId: { in: userWorkspaces.map((w) => w.tenantId) } }]
                : []),
            ],
          },
          orderBy: { updatedAt: 'desc' },
        })
        .catch(() => []);

      for (const sa of otherAccounts) {
        let meta: Record<string, any> = {};
        if (sa.metadata) {
          try {
            meta = typeof sa.metadata === 'string' ? JSON.parse(sa.metadata) : sa.metadata;
          } catch {}
        }
        const id = String(sa.accountId || meta.locationId || sa.id);
        if (knownIds.has(id)) continue;
        knownIds.add(id);
        const name = String(
          meta.locationTitle || sa.accountName?.replace(/\s*\([^)]*\)$/, '').trim() || 'Business Profile',
        );
        profiles.push({
          id,
          name,
          shortId: `#${id.slice(-4)}`,
          initial: name.charAt(0).toUpperCase() || 'B',
          category: typeof meta.category === 'string' ? meta.category : undefined,
        });
      }
    }

    const enrichedProfiles = profiles.map((p) => {
      const boundWs = userWorkspaces.find((w) => w.boundGbpLocationId === p.id) || null;
      return {
        ...p,
        boundWorkspaceId: boundWs?.workspaceId || null,
        boundBusinessName: boundWs?.name || null,
        boundBusinessSlug: boundWs?.slug || null,
        boundPlanTier: boundWs?.planTier || null,
        isBoundToCurrentWorkspace: Boolean(boundWs && boundWs.tenantId === user.tenantId),
        isBoundToOtherWorkspace: Boolean(boundWs && boundWs.tenantId !== user.tenantId),
      };
    });

    const boundProfileId =
      typeof tenantSettings.boundGbpLocationId === 'string' && tenantSettings.boundGbpLocationId
        ? tenantSettings.boundGbpLocationId
        : null;

    const activeProfileId = String(
      boundProfileId ||
        tenantSettings.activeGbpLocationId ||
        profiles.find((p) => p.isPrimary)?.id ||
        profiles[0]?.id || '',
    );
    const activeProfile = enrichedProfiles.find((p) => p.id === activeProfileId) || enrichedProfiles[0] || null;

    const activeSocialAccount = socialAccounts.find((sa) => {
      let meta: Record<string, any> = {};
      if (sa.metadata) {
        try {
          meta = typeof sa.metadata === 'string' ? JSON.parse(sa.metadata) : sa.metadata;
        } catch {}
      }
      const id = String(sa.accountId || meta.locationId || sa.id);
      return id === activeProfileId || sa.id === activeProfileId;
    });

    return NextResponse.json({
      email: googleEmail,
      count: enrichedProfiles.length,
      hasConnectedGbp: true,
      activeProfileId: activeProfile ? activeProfile.id : null,
      boundProfileId,
      hasWorkspaceActivity: currentWorkspaceActivity.hasActivity,
      workspaceActivityReason: currentWorkspaceActivity.reason,
      currentWorkspaceId: user.workspaceId || userWorkspaces.find((w) => w.isCurrent)?.workspaceId || null,
      workspaces: userWorkspaces,
      savedPublishingAccountId: tenantSettings.activeGbpLocationId ? activeSocialAccount?.id ?? null : null,
      activeProfile,
      profiles: enrichedProfiles,
      phone: tenant?.phone || '',
      version: 'BGOS v2.0',
    });
  } catch (err: unknown) {
    console.error('[api/gbp/accounts/discover] GET error:', err);
    return NextResponse.json({ error: 'Failed to discover Google Business accounts' }, { status: 500 });
  }
}

export async function POST(request: NextRequest) {
  try {
    const user = await getAuthUser(request);
    if (!user || !user.tenantId) {
      return NextResponse.json({ error: 'Authentication required' }, { status: 401 });
    }
    const tenantId = user.tenantId;

    const body = await request.json().catch(() => ({}));
    const profileId = String(body.profileId || '').trim();
    if (!profileId) {
      return NextResponse.json({ error: 'Profile ID is required' }, { status: 400 });
    }

    const customBusinessName = typeof body.businessName === 'string' ? body.businessName.trim() : '';
    const customCategory = typeof body.category === 'string' ? body.category.trim() : '';
    const customProducts = Array.isArray(body.products)
      ? body.products.filter((p): p is string => typeof p === 'string' && p.trim().length > 0).map((p) => p.trim())
      : undefined;
    const customServices = Array.isArray(body.services)
      ? body.services.filter((s): s is string => typeof s === 'string' && s.trim().length > 0).map((s) => s.trim())
      : undefined;

    const tenant = await db.tenant.findUnique({
      where: { id: user.tenantId },
      select: {
        id: true,
        name: true,
        slug: true,
        settingsJson: true,
        industry: true,
        state: true,
        country: true,
        address: true,
        city: true,
      },
    });

    let tenantSettings: Record<string, any> = {};
    if (tenant?.settingsJson) {
      try {
        tenantSettings = JSON.parse(tenant.settingsJson);
      } catch {}
    }

    // Find target social account (either already in current tenant or in another workspace owned by user)
    let targetAccount = await db.socialAccount.findFirst({
      where: {
        tenantId: user.tenantId,
        platform: 'googlebusiness',
        isActive: true,
        accountId: profileId,
      },
    });

    const userWorkspaces = await listUserBgosWorkspaces(
      user.id,
      user.workspaceId,
      user.tenantId,
    ).catch(() => []);

    if (!targetAccount) {
      const cloned = await cloneGoogleAccountToTenant(
        user.id,
        profileId,
        user.tenantId,
        userWorkspaces.map((w) => w.tenantId),
      ).catch(() => false);
      if (cloned) {
        targetAccount = await db.socialAccount.findFirst({
          where: {
            tenantId: user.tenantId,
            platform: 'googlebusiness',
            isActive: true,
            accountId: profileId,
          },
        });
      }
    }

    let targetName = 'Google Business';
    let gbpCategory = '';
    let gbpAddress = '';
    let gbpPlaceId = '';
    let gbpCity = '';
    if (targetAccount) {
      let meta: Record<string, any> = {};
      try {
        meta = typeof targetAccount.metadata === 'string' ? JSON.parse(targetAccount.metadata) : (targetAccount.metadata || {});
      } catch {}
      targetName = meta.locationTitle || targetAccount.accountName.replace(/\s*\([^)]*\)$/, '').trim();
      gbpCategory = meta.category || '';
      gbpAddress = meta.address || '';
      gbpPlaceId = meta.placeId || '';
      if (gbpAddress) {
        const parts = gbpAddress.split(',').map((s: string) => s.trim()).filter(Boolean);
        for (let i = parts.length - 1; i >= 0; i--) {
          const p = parts[i];
          if (/^\d{5,6}$/.test(p)) continue;
          if (/(bihar|uttar pradesh|haryana|delhi|maharashtra|karnataka|punjab|gujarat|tamil nadu|rajasthan|texas|california)/i.test(p)) continue;
          if (p.length > 2 && !/near|opp|behind|floor|suite|road|rd|chowk|street|st|lane|highway|nh/i.test(p)) {
            gbpCity = p;
            break;
          }
        }
        if (!gbpCity && parts.length > 2) gbpCity = parts[parts.length - 2];
      }
    }

    const boundProfileId =
      typeof tenantSettings.boundGbpLocationId === 'string' && tenantSettings.boundGbpLocationId
        ? tenantSettings.boundGbpLocationId
        : typeof tenantSettings.activeGbpLocationId === 'string' && tenantSettings.activeGbpLocationId
          ? tenantSettings.activeGbpLocationId
          : null;

    const activity = await hasWorkspaceLiveActivity(user.tenantId).catch(() => ({
      hasActivity: true,
      reason: 'active workspace data',
      counts: { leads: 0, customers: 0, bookings: 0, conversations: 0, publicChats: 0, reviews: 0, posts: 0 },
    }));

    if (boundProfileId && boundProfileId !== profileId) {
      const existingTarget = userWorkspaces.find(
        (w) => w.boundGbpLocationId === profileId && w.workspaceId !== user.workspaceId,
      );
      if (activity.hasActivity || !body.allowReplace) {
        return NextResponse.json(
          {
            error: activity.hasActivity
              ? `This workspace is locked to "${tenant?.name || 'your active business'}" (${activity.reason}). Add a separate Business Workspace for "${customBusinessName || targetName}".`
              : `This workspace is dedicated to "${tenant?.name || 'your existing business'}". Add a separate Business Workspace for "${customBusinessName || targetName}".`,
            code: 'WORKSPACE_BOUND_TO_OTHER_BUSINESS',
            boundProfileId,
            boundBusinessName: tenant?.name || null,
            hasLiveActivity: activity.hasActivity,
            activityReason: activity.reason,
            canReplaceUnusedWorkspace: !activity.hasActivity,
            existingTargetWorkspaceId: existingTarget?.workspaceId || null,
            existingTargetWorkspaceSlug: existingTarget?.slug || null,
          },
          { status: 409 },
        );
      }
    }

    if (targetAccount) {
      // Touch updatedAt so it sorts to the top
      await db.socialAccount.update({
        where: { id: targetAccount.id },
        data: { updatedAt: new Date() },
      });
    }

    const finalName = customBusinessName || targetName;

    // Resolve intelligent category: user input > GBP category (if not generic) > inferred from name
    let finalCategory = customCategory;
    if (!finalCategory) {
      if (gbpCategory && !/corporate|holding|community centre/i.test(gbpCategory)) {
        finalCategory = gbpCategory;
      } else if (/(market|grocery|supermarket|mart|kirana|retail|store|bazaar|provisions)/i.test(finalName)) {
        finalCategory = 'Grocery & Supermarket';
      } else if (/(pool|swimming|farmhouse|resort|villa|cottage|homestay|retreat)/i.test(finalName)) {
        finalCategory = 'Farmhouse & Resort';
      } else if (/(cake|bakery|pastry|dessert|mithai|sweet|patisserie)/i.test(finalName)) {
        finalCategory = 'Bakery & Cake Shop';
      } else if (/(hardware|tool|fastener|plumbing|sanitary|pipe)/i.test(finalName)) {
        finalCategory = 'Hardware & Tools';
      } else if (/(paint|color|wall finish|coating|decor)/i.test(finalName)) {
        finalCategory = 'Paint & Home Decor';
      } else if (gbpCategory) {
        finalCategory = gbpCategory;
      } else {
        finalCategory = 'Retail & Local Services';
      }
    }

    // Update tenant settings with active & bound profile
    tenantSettings.activeGbpLocationId = profileId;
    tenantSettings.boundGbpLocationId = profileId;
    tenantSettings.boundAt = tenantSettings.boundAt || new Date().toISOString();
    tenantSettings.activeGbpTitle = finalName;
    tenantSettings.activeGbpCategory = finalCategory;
    if (gbpAddress) tenantSettings.activeGbpAddress = gbpAddress;
    if (gbpCity) tenantSettings.activeGbpCity = gbpCity;
    if (gbpPlaceId) tenantSettings.activeGbpPlaceId = gbpPlaceId;
    if (customProducts) tenantSettings.activeGbpProducts = customProducts;
    if (customServices) tenantSettings.activeGbpServices = customServices;

    const nextAddress = gbpAddress || tenant?.address || null;
    const nextCity = gbpCity || tenant?.city || null;
    const sanitizedState = normalizeRegionState({
      state: tenant?.state ?? null,
      country: tenant?.country ?? null,
      address: nextAddress,
      city: nextCity,
    });

    const nextSlug =
      !activity.hasActivity && tenant?.slug && looksLikeAutoGeneratedFallbackSlug(tenant.slug)
        ? await ensureUniqueBgosWorkspaceSlug(finalName, user.tenantId, user.workspaceId || undefined)
        : tenant?.slug;

    // Atomically synchronize Tenant, Workspace and BrandProfile
    await Promise.all([
      db.tenant.update({
        where: { id: user.tenantId },
        data: {
          settingsJson: JSON.stringify(tenantSettings),
          industry: finalCategory,
          name: finalName,
          ...(nextSlug && nextSlug !== tenant?.slug ? { slug: nextSlug } : {}),
          ...(gbpAddress ? { address: gbpAddress } : {}),
          ...(gbpCity ? { city: gbpCity } : {}),
          ...(gbpPlaceId ? { googlePlaceId: gbpPlaceId } : {}),
          ...(sanitizedState !== (tenant?.state ?? null) ? { state: sanitizedState } : {}),
        },
      }),
      db.workspace
        .updateMany({
          where: { tenantId: user.tenantId },
          data: {
            name: finalName,
            industry: finalCategory,
            ...(nextSlug && nextSlug !== tenant?.slug ? { slug: nextSlug } : {}),
          },
        })
        .catch(() => {}),
      // Purge cached competitors so the new profile loads fresh local competitors
      db.competitor.deleteMany({ where: { tenantId: user.tenantId } }).catch(() => {}),
      (async () => {
        const existingBp = await db.brandProfile.findUnique({ where: { tenantId } }).catch(() => null);
        const dataToSave: any = {
          businessName: finalName,
          industry: finalCategory,
          ...(gbpCity ? { location: gbpCity } : {}),
        };
        if (customProducts) dataToSave.products = JSON.stringify(customProducts);
        if (customServices) dataToSave.services = JSON.stringify(customServices);

        if (existingBp) {
          await db.brandProfile.update({
            where: { id: existingBp.id },
            data: dataToSave,
          });
        } else {
          await db.brandProfile.create({
            data: {
              tenantId,
              ...dataToSave,
            },
          });
        }
      })(),
    ]);

    invalidatePlacePayloadCache(user.tenantId);
    await ensureAndSyncBusinessChatbot(user.tenantId, {
      triggerSource: 'gbp_profile_bound',
    }).catch(() => {});

    const targetShortId = `#${profileId.slice(-4)}`;
    const targetProfile: GbpDiscoveredProfile = {
      id: profileId,
      name: finalName,
      shortId: targetShortId,
      initial: finalName.charAt(0).toUpperCase() || 'B',
      category: finalCategory,
    };

    return NextResponse.json({
      success: true,
      activeProfileId: profileId,
      boundProfileId: profileId,
      slug: nextSlug || tenant?.slug || null,
      activeProfile: targetProfile,
      message: `Switched active Google Business Profile to ${finalName} (${targetShortId})`,
    });
  } catch (err: unknown) {
    console.error('[api/gbp/accounts/discover] POST error:', err);
    return NextResponse.json({ error: 'Failed to switch profile' }, { status: 500 });
  }
}
