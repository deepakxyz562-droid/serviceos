/**
 * Helper to resolve text based on current language mode.
 */
export function getBosText(
  key: string,
  lang: BosLanguage = 'en',
  fallbackEn?: string,
  fallbackHi?: string
): string {
  const item = BOS_TRANSLATIONS[key];
  const en = item ? item.en : (fallbackEn || key);
  const hi = item ? item.hi : (fallbackHi || fallbackEn || key);

  if (lang === 'hi') {
    return hi;
  }
  if (lang === 'both') {
    if (item && item.both) return item.both;
    // Don't duplicate if identical (e.g. GSTIN, UPI)
    if (en.trim().toLowerCase() === hi.trim().toLowerCase()) return en;
    return `${en} / ${hi}`;
  }
  return en;
}
