export interface BgosWorkspaceSummary {
  workspaceId: string;
  tenantId: string;
  name: string;
  slug: string;
  industry: string | null;
  logo: string | null;
  boundGbpLocationId: string | null;
  boundBusinessName: string | null;
  planTier: string;
  subscriptionStatus: string;
  trialEndsAt: string | null;
  isCurrent: boolean;
  hasLiveActivity: boolean;
  publicBusinessUrl: string;
}

export interface WorkspaceLiveActivityResult {
  hasActivity: boolean;
  reason: string | null;
  counts: {
    leads: number;
    customers: number;
    bookings: number;
    conversations: number;
    publicChats: number;
    reviews: number;
    posts: number;
  };
}

export function parseWorkspaceJson(raw?: string | null): Record<string, any> {
  if (!raw || typeof raw !== 'string') return {};
  try {
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {};
  } catch {
    return {};
  }
}

export function buildPublicBusinessPath(slug: string): string {
  return `/b/${slug}`;
}

export function normalizeSlugCandidate(raw: string): string {
  const cleaned = raw
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 46);
  return cleaned || 'business';
}

export function looksLikeAutoGeneratedFallbackSlug(slug: string): boolean {
  return /^(business|workspace|[a-z0-9-]+-workspace)(-\d+)?$/i.test(slug.trim());
}

export async function ensureUniqueBgosWorkspaceSlug(
  baseName: string,
  excludeTenantId?: string,
  excludeWorkspaceId?: string,
): Promise<string> {
  const base = normalizeSlugCandidate(baseName);
  for (let i = 0; i < 8; i++) {
    const candidate = i === 0 ? base : i <= 5 ? `${base}-${i + 1}` : `${base}-${randomBytes(2).toString('hex')}`;
    const [existingTenant, existingWorkspace] = await Promise.all([
      db.tenant.findFirst({
        where: {
          slug: candidate,
          ...(excludeTenantId ? { NOT: { id: excludeTenantId } } : {}),
        },
        select: { id: true },
      }),
      db.workspace.findFirst({
        where: {
          slug: candidate,
          ...(excludeWorkspaceId ? { NOT: { id: excludeWorkspaceId } } : {}),
        },
        select: { id: true },
      }),
    ]);

    if (!existingTenant && !existingWorkspace) {
      return candidate;
    }
  }
  return `${base}-${randomBytes(3).toString('hex')}`;
}

export async function hasWorkspaceLiveActivity(
  tenantId: string,
): Promise<WorkspaceLiveActivityResult> {
  const [leads, customers, bookings, conversations, publicChats, reviews, posts] = await Promise.all([
    db.lead.count({ where: { tenantId } }).catch(() => 0),
    db.customer.count({ where: { tenantId } }).catch(() => 0),
    db.booking.count({ where: { tenantId, deletedAt: null } }).catch(() => 0),
    db.conversation.count({ where: { tenantId } }).catch(() => 0),
    db.publicChatSession.count({ where: { tenantId } }).catch(() => 0),
    db.review.count({ where: { tenantId } }).catch(() => 0),
    db.socialPost.count({ where: { tenantId } }).catch(() => 0),
  ]);

  const counts = {
    leads,
    customers,
    bookings,
    conversations,
    publicChats,
    reviews,
    posts,
  };

  const reasons: string[] = [];
  if (leads > 0) reasons.push(`${leads} lead(s)`);
  if (customers > 0) reasons.push(`${customers} customer(s)`);
  if (bookings > 0) reasons.push(`${bookings} appointment(s)`);
  if (conversations > 0 || publicChats > 0) reasons.push('customer chats');
  if (reviews > 0) reasons.push(`${reviews} synced review(s)`);
  if (posts > 0) reasons.push(`${posts} social post(s)`);

  return {
    hasActivity: reasons.length > 0,
    reason: reasons.length > 0 ? reasons.join(', ') : null,
    counts,
  };
}

/**
 * Checks whether `userId` owns or holds membership in `targetWorkspaceId` (within BGOS).
 */
export async function resolveUserOwnedBgosWorkspace(userId: string, targetWorkspaceId: string) {
  const workspace = await db.workspace.findUnique({
    where: { id: targetWorkspaceId },
    include: {
      tenant: {
        select: {
          id: true,
          name: true,
          slug: true,
          industry: true,
          logo: true,
          settingsJson: true,
          plan: true,
          planStatus: true,
          trialEndsAt: true,
          suspendedAt: true,
        },
      },
    },
  });

  if (!workspace || !workspace.tenant || workspace.tenant.suspendedAt) {
    return null;
  }

  const [membership, productWs] = await Promise.all([
    db.productMembership
      .findFirst({
        where: { userId, workspaceId: targetWorkspaceId, status: 'active' },
      })
      .catch(() => null),
    db.productWorkspace
      .findFirst({
        where: { workspaceId: targetWorkspaceId, product: 'bgos' },
      })
      .catch(() => null),
  ]);

  if (membership && (productWs || workspace.productType === 'bgos' || workspace.productType === 'both')) {
    return {
      workspace,
      tenant: workspace.tenant,
      productWorkspace: productWs,
      role: membership.role,
    };
  }

  // Fallback for workspaces owned directly via Workspace.ownerId / active user pointer
  const user = await db.user.findUnique({
    where: { id: userId },
    select: { id: true, workspaceId: true, tenantId: true, role: true },
  });

  const isDirectOwner = workspace.ownerId === userId || user?.workspaceId === targetWorkspaceId;
  if (!isDirectOwner) return null;

  const tenantSettings = parseWorkspaceJson(workspace.tenant.settingsJson);
  const isBgos =
    workspace.productType === 'bgos' ||
    workspace.productType === 'both' ||
    tenantSettings.source === 'bgos' ||
    Boolean(tenantSettings.isBgosStandalone);
  if (!isBgos && workspace.productType !== 'crm') return null;

  return {
    workspace,
    tenant: workspace.tenant,
    productWorkspace: productWs,
    role: user?.role || 'owner',
  };
}

export async function listUserBgosWorkspaces(
  userId: string,
  currentWorkspaceId?: string | null,
  currentTenantId?: string | null,
): Promise<BgosWorkspaceSummary[]> {
  const [userRow, memberships, ownedWorkspaces] = await Promise.all([
    db.user.findUnique({
      where: { id: userId },
      select: { workspaceId: true, tenantId: true },
    }),
    db.productMembership
      .findMany({
        where: { userId, status: 'active' },
        select: { workspaceId: true },
        orderBy: { createdAt: 'asc' },
      })
      .catch(() => []),
    db.workspace
      .findMany({
        where: { ownerId: userId },
        include: {
          tenant: {
            select: {
              id: true,
              name: true,
              slug: true,
              industry: true,
              logo: true,
              settingsJson: true,
              plan: true,
              planStatus: true,
              trialEndsAt: true,
              suspendedAt: true,
            },
          },
        },
        orderBy: { createdAt: 'asc' },
      })
      .catch(() => []),
  ]);

  const effectiveCurrentWsId = currentWorkspaceId || userRow?.workspaceId || null;
  const effectiveCurrentTenantId = currentTenantId || userRow?.tenantId || null;

  const memberWsIds = memberships.map((m) => m.workspaceId).filter(Boolean);
  const bgosProductWsList = memberWsIds.length
    ? await db.productWorkspace
        .findMany({
          where: { workspaceId: { in: memberWsIds }, product: 'bgos' },
          select: { workspaceId: true },
        })
        .catch(() => [])
    : [];

  const candidateWorkspaceIds = new Set<string>();
  for (const pw of bgosProductWsList) {
    candidateWorkspaceIds.add(pw.workspaceId);
  }
  for (const w of ownedWorkspaces) {
    const settings = parseWorkspaceJson(w.tenant?.settingsJson);
    const isBgos =
      w.productType === 'bgos' ||
      w.productType === 'both' ||
      settings.source === 'bgos' ||
      Boolean(settings.isBgosStandalone) ||
      w.id === effectiveCurrentWsId;
    if (isBgos && !w.tenant?.suspendedAt) {
      candidateWorkspaceIds.add(w.id);
    }
  }
  if (effectiveCurrentWsId) {
    candidateWorkspaceIds.add(effectiveCurrentWsId);
  }

  const wsIdArray = Array.from(candidateWorkspaceIds);
  const [allWorkspaces, prodSubscriptions] = wsIdArray.length
    ? await Promise.all([
        db.workspace.findMany({
          where: { id: { in: wsIdArray } },
          include: {
            tenant: {
              select: {
                id: true,
                name: true,
                slug: true,
                industry: true,
                logo: true,
                settingsJson: true,
                plan: true,
                planStatus: true,
                trialEndsAt: true,
                suspendedAt: true,
              },
            },
          },
          orderBy: { createdAt: 'asc' },
        }),
        db.productSubscription
          .findMany({
            where: { workspaceId: { in: wsIdArray } },
            select: {
              workspaceId: true,
              plan: true,
              status: true,
              trialEndsAt: true,
            },
          })
          .catch(() => []),
      ])
    : [[], []];

  const subByWsId = new Map<string, (typeof prodSubscriptions)[number]>();
  for (const sub of prodSubscriptions) {
    subByWsId.set(sub.workspaceId, sub);
  }

  const summaries = await Promise.all(
    allWorkspaces
      .filter((w) => Boolean(w.tenant) && !w.tenant?.suspendedAt)
      .map(async (w) => {
        const tenant = w.tenant!;
        const settings = parseWorkspaceJson(tenant.settingsJson);
        const sub = subByWsId.get(w.id) || null;

        const boundGbpLocationId =
          typeof settings.boundGbpLocationId === 'string' && settings.boundGbpLocationId
            ? settings.boundGbpLocationId
            : typeof settings.activeGbpLocationId === 'string' && settings.activeGbpLocationId
              ? settings.activeGbpLocationId
              : null;

        const activity = await hasWorkspaceLiveActivity(tenant.id).catch(() => ({
          hasActivity: false,
          reason: null,
          counts: {
            leads: 0,
            customers: 0,
            bookings: 0,
            conversations: 0,
            publicChats: 0,
            reviews: 0,
            posts: 0,
          },
        }));

        const isCurrent =
          effectiveCurrentWsId ? w.id === effectiveCurrentWsId : tenant.id === effectiveCurrentTenantId;

        return {
          workspaceId: w.id,
          tenantId: tenant.id,
          name: tenant.name || w.name,
          slug: tenant.slug || w.slug,
          industry: tenant.industry || w.industry || null,
          logo: tenant.logo || w.logo || null,
          boundGbpLocationId,
          boundBusinessName: boundGbpLocationId ? tenant.name || w.name : null,
          planTier: sub?.plan || tenant.plan || 'free',
          subscriptionStatus: sub?.status || tenant.planStatus || 'active',
          trialEndsAt: (sub?.trialEndsAt || tenant.trialEndsAt)?.toISOString?.() ?? null,
          isCurrent,
          hasLiveActivity: activity.hasActivity,
          publicBusinessUrl: buildPublicBusinessPath(tenant.slug || w.slug),
        } satisfies BgosWorkspaceSummary;
      }),
  );

  return summaries.sort((a, b) => {
    if (a.isCurrent && !b.isCurrent) return -1;
    if (!a.isCurrent && b.isCurrent) return 1;
    return a.name.localeCompare(b.name);
  });
}

export async function cloneGoogleAccountToTenant(
  userId: string,
  profileId: string,
  targetTenantId: string,
  sourceTenantIds: string[],
): Promise<boolean> {
  const source = await db.socialAccount.findFirst({
    where: {
      platform: 'googlebusiness',
      isActive: true,
      accountId: profileId,
      OR: [
        { connectedById: userId },
        ...(sourceTenantIds.length > 0 ? [{ tenantId: { in: sourceTenantIds } }] : []),
      ],
    },
    orderBy: { updatedAt: 'desc' },
  });

  if (!source) return false;

  await db.socialAccount.upsert({
    where: {
      tenantId_platform_accountId: {
        tenantId: targetTenantId,
        platform: 'googlebusiness',
        accountId: source.accountId,
      },
    },
    update: {
      accountName: source.accountName,
      accessToken: source.accessToken,
      refreshToken: source.refreshToken,
      tokenExpiry: source.tokenExpiry,
      scopes: source.scopes,
      metadata: source.metadata,
      connectedById: userId,
      isActive: true,
    },
    create: {
      tenantId: targetTenantId,
      platform: 'googlebusiness',
      accountId: source.accountId,
      accountName: source.accountName,
      accessToken: source.accessToken,
      refreshToken: source.refreshToken,
      tokenExpiry: source.tokenExpiry,
      scopes: source.scopes,
      metadata: source.metadata,
      connectedById: userId,
      isActive: true,
    },
  });

  return true;
}

export interface CreateBgosWorkspaceInput {
  userId: string;
  businessName: string;
  profileId?: string | null;
  category?: string | null;
  phone?: string | null;
  address?: string | null;
  city?: string | null;
  state?: string | null;
  country?: string | null;
  currency?: string | null;
  website?: string | null;
  services?: string[];
  activateForUser?: boolean;
}

export async function createBgosBusinessWorkspace(input: CreateBgosWorkspaceInput) {
  const cleanName = input.businessName.trim();
  if (!cleanName) {
    throw new Error('Business name is required.');
  }

  const userWorkspaces = await listUserBgosWorkspaces(input.userId);

  if (input.profileId) {
    const existingBound = userWorkspaces.find((w) => w.boundGbpLocationId === input.profileId);
    if (existingBound) {
      const switched = await switchUserBgosWorkspace(input.userId, existingBound.workspaceId);
      return {
        alreadyExisted: true,
        workspace: existingBound,
        switched,
      };
    }
  }

  const uniqueSlug = await ensureUniqueBgosWorkspaceSlug(cleanName);
  const country = (input.country || 'IN').trim().toUpperCase();
  const currency = (input.currency || (country === 'IN' ? 'INR' : 'USD')).trim().toUpperCase();
  const category = (input.category || 'Local Business').trim();

  const initialSettings = {
    source: 'bgos',
    isBgosStandalone: true,
    boundGbpLocationId: input.profileId || null,
    activeGbpLocationId: input.profileId || null,
    boundAt: input.profileId ? new Date().toISOString() : null,
    city: input.city || null,
    state: input.state || null,
    website: input.website || null,
    publicCard: {
      accentColor: '#1E3A5F',
      tagline: category,
      showReviews: true,
      showGallery: true,
      bookingEnabled: true,
    },
  };

  const created = await db.$transaction(async (tx) => {
    const tenant = await tx.tenant.create({
      data: {
        name: cleanName,
        slug: uniqueSlug,
        industry: category,
        phone: input.phone || null,
        address: input.address || null,
        city: input.city || null,
        state: input.state || null,
        country,
        currency,
        plan: 'free',
        planStatus: 'active',
        onboardingCompleted: Boolean(input.profileId),
        onboardingStep: input.profileId ? 3 : 0,
        settingsJson: JSON.stringify(initialSettings),
      },
    });

    const workspace = await tx.workspace.create({
      data: {
        tenantId: tenant.id,
        name: cleanName,
        slug: uniqueSlug,
        industry: category,
        ownerId: input.userId,
        productType: 'bgos',
        plan: 'free',
      },
    });

    const productWorkspace = await tx.productWorkspace.create({
      data: {
        workspaceId: workspace.id,
        product: 'bgos',
        tenantId: tenant.id,
        status: 'active',
        onboardingCompleted: Boolean(input.profileId),
        onboardingStep: input.profileId ? 3 : 0,
      },
    });

    await tx.productMembership.create({
      data: {
        id: `pm_${randomBytes(8).toString('hex')}`,
        workspaceId: workspace.id,
        userId: input.userId,
        role: 'owner',
        status: 'active',
      },
    });

    await tx.productSubscription.create({
      data: {
        workspaceId: workspace.id,
        plan: 'free',
        status: 'active',
        billingSource: 'none',
      },
    });

    if (input.activateForUser !== false) {
      await tx.user.update({
        where: { id: input.userId },
        data: {
          tenantId: tenant.id,
          workspaceId: workspace.id,
        },
      });
    }

    return { tenant, workspace, productWorkspace };
  });

  if (input.profileId) {
    await cloneGoogleAccountToTenant(
      input.userId,
      input.profileId,
      created.tenant.id,
      userWorkspaces.map((w) => w.tenantId),
    ).catch((err) => {
      console.warn('[bgos-workspaces] cloneGoogleAccountToTenant failed:', err);
    });
  }

  await db.brandProfile
    .upsert({
      where: { tenantId: created.tenant.id },
      update: {
        businessName: cleanName,
        industry: category,
        location: [input.city, input.state].filter(Boolean).join(', ') || input.address || null,
        website: input.website || null,
        services: input.services?.length ? JSON.stringify(input.services) : undefined,
      },
      create: {
        tenantId: created.tenant.id,
        businessName: cleanName,
        industry: category,
        location: [input.city, input.state].filter(Boolean).join(', ') || input.address || null,
        website: input.website || null,
        tone: 'friendly',
        services: input.services?.length ? JSON.stringify(input.services) : undefined,
      },
    })
    .catch(() => null);

  if (input.services && input.services.length > 0) {
    for (const svcName of input.services.slice(0, 12)) {
      const cleanSvc = svcName.trim();
      if (!cleanSvc) continue;
      await db.service
        .create({
          data: {
            tenantId: created.tenant.id,
            name: cleanSvc,
            category,
            basePrice: 0,
            duration: 60,
            isActive: true,
          },
        })
        .catch(() => null);
    }
  }

  await ensureAndSyncBusinessChatbot(created.tenant.id, {
    triggerSource: 'workspace_created',
  }).catch(() => null);

  const summary: BgosWorkspaceSummary = {
    workspaceId: created.workspace.id,
    tenantId: created.tenant.id,
    name: cleanName,
    slug: uniqueSlug,
    industry: category,
    logo: null,
    boundGbpLocationId: input.profileId || null,
    boundBusinessName: input.profileId ? cleanName : null,
    planTier: 'free',
    subscriptionStatus: 'active',
    trialEndsAt: null,
    isCurrent: input.activateForUser !== false,
    hasLiveActivity: false,
    publicBusinessUrl: buildPublicBusinessPath(uniqueSlug),
  };

  return {
    alreadyExisted: false,
    workspace: summary,
    created,
  };
}

export async function switchUserBgosWorkspace(userId: string, targetWorkspaceId: string) {
  const resolved = await resolveUserOwnedBgosWorkspace(userId, targetWorkspaceId);
  if (!resolved) {
    return null;
  }

  const user = await db.user.update({
    where: { id: userId },
    data: {
      tenantId: resolved.tenant.id,
      workspaceId: resolved.workspace.id,
    },
    select: {
      id: true,
      email: true,
      name: true,
      role: true,
      tenantId: true,
      workspaceId: true,
      avatar: true,
      isSuperAdmin: true,
      phone: true,
    },
  });

  const authUser: AuthUser = {
    id: user.id,
    email: user.email,
    name: user.name,
    role: resolved.role || user.role,
    tenantId: resolved.tenant.id,
    workspaceId: resolved.workspace.id,
    avatar: user.avatar,
    isSuperAdmin: Boolean(user.isSuperAdmin),
    phone: user.phone,
    employeeId: null,
  };

  return {
    authUser,
    workspace: resolved.workspace,
    tenant: resolved.tenant,
    productWorkspace: resolved.productWorkspace,
  };
}

export async function issueSessionForSwitchedWorkspace(
  authUser: AuthUser,
  metadata: RefreshSessionMetadata = {},
) {
  const accessToken = generateToken(authUser);
  const refresh = await issueRefreshSession({ type: 'user', id: authUser.id }, metadata);
  return {
    token: accessToken,
    accessToken,
    refreshToken: refresh.token,
    user: authUser,
  };
}
