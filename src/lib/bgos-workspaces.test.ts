import { beforeEach, describe, expect, it, vi } from 'vitest';

const { mockDb, mockSyncChatbot } = vi.hoisted(() => ({
  mockDb: {
    lead: { count: vi.fn() },
    customer: { count: vi.fn() },
    booking: { count: vi.fn() },
    conversation: { count: vi.fn() },
    publicChatSession: { count: vi.fn() },
    review: { count: vi.fn() },
    socialPost: { count: vi.fn() },
    user: { findUnique: vi.fn(), update: vi.fn() },
    workspace: { findFirst: vi.fn(), findUnique: vi.fn(), findMany: vi.fn(), create: vi.fn() },
    tenant: { findFirst: vi.fn(), create: vi.fn() },
    productWorkspace: { findFirst: vi.fn(), findMany: vi.fn(), create: vi.fn() },
    productMembership: { findFirst: vi.fn(), findMany: vi.fn(), create: vi.fn() },
    productSubscription: { findMany: vi.fn(), create: vi.fn() },
    socialAccount: { findFirst: vi.fn(), upsert: vi.fn() },
    brandProfile: { upsert: vi.fn() },
    service: { create: vi.fn() },
    $transaction: vi.fn(),
  },
  mockSyncChatbot: vi.fn().mockResolvedValue({}),
}));

vi.mock('@/lib/db', () => ({ db: mockDb }));
vi.mock('@/lib/bgos-business-chatbot', () => ({
  ensureAndSyncBusinessChatbot: mockSyncChatbot,
}));

import {
  createBgosBusinessWorkspace,
  hasWorkspaceLiveActivity,
  looksLikeAutoGeneratedFallbackSlug,
  switchUserBgosWorkspace,
} from '@/lib/bgos-workspaces';

describe('bgos-workspaces (1-business isolation & switcher)', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mockDb.lead.count.mockResolvedValue(0);
    mockDb.customer.count.mockResolvedValue(0);
    mockDb.booking.count.mockResolvedValue(0);
    mockDb.conversation.count.mockResolvedValue(0);
    mockDb.publicChatSession.count.mockResolvedValue(0);
    mockDb.review.count.mockResolvedValue(0);
    mockDb.socialPost.count.mockResolvedValue(0);

    mockDb.user.findUnique.mockResolvedValue({ workspaceId: 'ws_1', tenantId: 'ten_1' });
    mockDb.productMembership.findMany.mockResolvedValue([]);
    mockDb.workspace.findMany.mockResolvedValue([]);
    mockDb.tenant.findFirst.mockResolvedValue(null);
    mockDb.workspace.findFirst.mockResolvedValue(null);
    mockDb.productWorkspace.findFirst.mockResolvedValue(null);
    mockDb.productWorkspace.findMany.mockResolvedValue([]);
    mockDb.productSubscription.findMany.mockResolvedValue([]);
    mockDb.brandProfile.upsert.mockResolvedValue({});
  });

  it('detects auto-generated fallback workspace slugs accurately', () => {
    expect(looksLikeAutoGeneratedFallbackSlug('deepak-chandras-workspace-1')).toBe(true);
    expect(looksLikeAutoGeneratedFallbackSlug('business-2')).toBe(true);
    expect(looksLikeAutoGeneratedFallbackSlug('kanvi-farmhouse')).toBe(false);
  });

  it('reports live workspace activity when any CRM, booking, review, post, or chat count > 0', async () => {
    mockDb.lead.count.mockResolvedValue(2);
    const active = await hasWorkspaceLiveActivity('ten_1');
    expect(active.hasActivity).toBe(true);
    expect(active.reason).toContain('2 lead(s)');

    mockDb.lead.count.mockResolvedValue(0);
    const empty = await hasWorkspaceLiveActivity('ten_1');
    expect(empty.hasActivity).toBe(false);
    expect(empty.reason).toBeNull();
  });

  it('provisions isolated tenant + workspace + free subscription + cloned GBP socialAccount on createBgosBusinessWorkspace', async () => {
    const txMock = {
      tenant: { create: vi.fn().mockResolvedValue({ id: 'ten_new', slug: 'royal-salon', name: 'Royal Salon' }) },
      workspace: { create: vi.fn().mockResolvedValue({ id: 'ws_new', slug: 'royal-salon', name: 'Royal Salon' }) },
      productWorkspace: { create: vi.fn().mockResolvedValue({ id: 'pw_new', slug: 'royal-salon' }) },
      productMembership: { create: vi.fn().mockResolvedValue({}) },
      productSubscription: { create: vi.fn().mockResolvedValue({}) },
      user: { update: vi.fn().mockResolvedValue({}) },
    };
    mockDb.$transaction.mockImplementation(async (fn: any) => fn(txMock));
    mockDb.socialAccount.findFirst.mockResolvedValue({
      accountId: 'loc_999',
      accountName: 'Royal Salon',
      accessToken: 'enc_access',
      refreshToken: 'enc_refresh',
      tokenExpiry: null,
      scopes: 'gbp',
      metadata: '{}',
    });
    mockDb.socialAccount.upsert.mockResolvedValue({});

    const res = await createBgosBusinessWorkspace({
      userId: 'usr_1',
      businessName: 'Royal Salon',
      profileId: 'loc_999',
      category: 'Beauty Salon',
      country: 'IN',
    });

    expect(res.alreadyExisted).toBe(false);
    expect(res.workspace.workspaceId).toBe('ws_new');
    expect(res.workspace.planTier).toBe('free');
    expect(txMock.productSubscription.create).toHaveBeenCalledWith({
      data: expect.objectContaining({
        plan: 'free',
        status: 'active',
      }),
    });
    expect(mockDb.socialAccount.upsert).toHaveBeenCalledWith(
      expect.objectContaining({
        where: {
          tenantId_platform_accountId: {
            tenantId: 'ten_new',
            platform: 'googlebusiness',
            accountId: 'loc_999',
          },
        },
      }),
    );
    expect(mockSyncChatbot).toHaveBeenCalledWith('ten_new', { triggerSource: 'workspace_created' });
  });

  it('denies workspace switching when user is neither owner nor member', async () => {
    mockDb.workspace.findUnique.mockResolvedValue({
      id: 'ws_foreign',
      ownerId: 'other_user',
      productType: 'bgos',
      tenant: { id: 'ten_foreign', suspendedAt: null, settingsJson: '{}' },
    });
    mockDb.productMembership.findFirst.mockResolvedValue(null);
    mockDb.user.findUnique.mockResolvedValue({ id: 'usr_1', workspaceId: 'ws_1', tenantId: 'ten_1', role: 'owner' });

    const switched = await switchUserBgosWorkspace('usr_1', 'ws_foreign');
    expect(switched).toBeNull();
    expect(mockDb.user.update).not.toHaveBeenCalled();
  });
});
